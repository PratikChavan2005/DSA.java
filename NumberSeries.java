import java.util.*;
class NumberSeries{
		
		public static void main(String[]args){
			
			int N=16;
			N=N-1;
			
					
							
						
					       if (N%2==0){
						int x=N/2;
						 double a=Math.pow(2,x);
							System.out.print(a);
						}
					
						else{
						int y=(N+1)/2;
						double b=Math.pow(3,(y-1));
							System.out.print(b);
							}
						
							
					
		
				
	
	}	
	
}